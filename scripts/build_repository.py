"""Build Kodi's update feed and installer. Run build.py first (stdlib only)."""
import argparse
import hashlib
import io
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
BASE_URL = 'https://raw.githubusercontent.com/wouterokkerse/Odido-TV-Kodi-Addon/kodi-repository/'


def version(value):
    if not re.fullmatch(r'\d+(?:\.\d+){0,3}', value):
        raise ValueError('Release versions must use numeric dotted notation')
    parts = tuple(map(int, value.split('.')))
    return parts + (0,) * max(0, 4 - len(parts))


def archive_files(files):
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w') as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 10, 17, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data)
    return stream.getvalue()


def build(output, root=ROOT):
    output, root = Path(output), Path(root)
    plugin = ET.parse(root / 'plugin.video.odidotv/addon.xml').getroot()
    repository = ET.parse(root / 'repository.odidotv/addon.xml').getroot()
    assert plugin.get('id') == 'plugin.video.odidotv'
    assert repository.get('id') == 'repository.odidotv'
    for element, expected in (('info', BASE_URL + 'addons.xml'),
                              ('checksum', BASE_URL + 'addons.xml.md5'),
                              ('datadir', BASE_URL)):
        assert repository.find('extension/dir/' + element).text == expected
    updates = {}
    manifests = (plugin, repository)
    existing = output / 'addons.xml'
    previous = {addon.get('id'): addon.get('version') for addon in
                ET.parse(existing).getroot()} if existing.exists() else {}
    for manifest in manifests:
        identifier, release = manifest.get('id'), manifest.get('version')
        if identifier in previous and version(release) < version(previous[identifier]):
            raise ValueError('Refusing to downgrade ' + identifier)
        version(release)
        if identifier == 'plugin.video.odidotv':
            data = (root / 'dist' / (identifier + '-' + release + '.zip')).read_bytes()
        else:
            files = {identifier + '/' + path.name: path.read_bytes()
                     for path in (root / identifier).iterdir() if path.is_file()}
            files[identifier + '/LICENSE'] = (root / 'LICENSE').read_bytes()
            data = archive_files(files)
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            assert archive.testzip() is None
            assert all(name.startswith(identifier + '/') and '..' not in Path(name).parts
                       for name in archive.namelist())
            packaged = ET.fromstring(archive.read(identifier + '/addon.xml'))
            assert ET.tostring(packaged) == ET.tostring(manifest), 'Stale package: run build.py'
        relative = identifier + '/' + identifier + '-' + release + '.zip'
        target = output / relative
        if target.exists() and target.read_bytes() != data:
            raise ValueError('Package changed without a version bump: ' + relative)
        updates[relative] = data
        updates[relative + '.md5'] = (hashlib.md5(data).hexdigest() + '\n').encode()
        updates[relative + '.sha256'] = (hashlib.sha256(data).hexdigest() + '  ' + Path(relative).name + '\n').encode()
        updates[identifier + '/addon.xml'] = ET.tostring(manifest, encoding='utf-8', xml_declaration=True)
        updates[identifier + '/icon.png'] = (root / identifier / 'icon.png').read_bytes()
    index = ET.Element('addons')
    index.extend(manifests)
    xml = ET.tostring(index, encoding='utf-8', xml_declaration=True) + b'\n'
    updates['addons.xml'] = xml
    # Kodi uses MD5 as its repository index change indicator.
    updates['addons.xml.md5'] = (hashlib.md5(xml).hexdigest() + '\n').encode()
    updates['README.md'] = (
        '# Odido TV Kodi repository\n\n'
        'Generated by GitHub Actions. Do not edit packages on this branch.\n\n'
        'Download [the repository installer](repository.odidotv/repository.odidotv-'
        + repository.get('version') + '.zip?raw=true), install it using Kodi → Add-ons → '
        'Install from zip file, then Install from repository → Odido TV Repository → '
        'Video add-ons → Odido TV (unofficial). Enable automatic updates in Kodi.\n'
    ).encode('utf-8')
    for relative, data in updates.items():
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print('Published feed for ' + ', '.join(m.get('id') + ' ' + m.get('version') for m in manifests))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist/kodi-repository')
    build(parser.parse_args().output)
